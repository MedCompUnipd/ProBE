def check(repo: Path, dp_binary: Path) -> None:
    if not (repo / "scripts/pipeline/06C1_finalize_directional_glocal.py").is_file():
        raise ValueError("Wrong source repository")
    with tempfile.TemporaryDirectory(prefix="probe-v2-native-chain-") as temp_name:
        temp = Path(temp_name)
        fixture = create_synthetic_inputs(temp, repo)
        if not dp_binary.is_file():
            raise ValueError("Original scientific 06C0 full DP binary is missing")
        completion = temp / "completion"
        report = execute_alignment_v2(
            workload=fixture["workload"],
            targets=fixture["targets"],
            taxonomy={
                role: fixture["taxonomy"][release]
                for role, release in fixture["releases"].items()
            },
            lineage_index=fixture["lineage_index"],
            lineage_paths=fixture["lineage"],
            nonexact_script=repo / "scripts/pipeline/NONEXACT_select_alignment_jobs.py",
            full_dp_binary=dp_binary,
            finalize_script=(
                repo / "scripts/pipeline/06C1_finalize_directional_glocal.py"
            ),
            destination=completion,
        )
        if report["dp_chunks"] < 1:
            raise AssertionError("Documentary NONEXACT did not invoke full DP")
        print("CANONICAL_06C_EXACT_AND_NONEXACT_DP=PASS")
        stage07 = fixture["m8_inputs"]["stage07_bundle"]
        science = publish_canonical_stage07(
            workload=fixture["workload"],
            completion=completion,
            targets=fixture["targets"],
            taxonomy_paths=fixture["taxonomy"],
            anchor_paths=fixture["anchors"],
            lineage_index=fixture["lineage_index"],
            lineage_paths=fixture["lineage"],
            policy="same_species_exact",
            destination=stage07,
        )
        if science["candidate_count"] != 3:
            raise AssertionError("Native V2 Stage 07 lost candidate coverage")
        validate_bundle(stage07, deep=True)
        donors = read_accepted_associations(
            stage07 / "07_accepted_associations.tsv",
            start_release_id="2023_01",
            end_release_id="2026_03",
            source_database="UniProtKB",
        )
        grouped = {release: 0 for release in ("2023_01", "2026_03")}
        for donor in donors.associations:
            grouped[donor.release] += int(donor.may_donate)
        if grouped != {"2023_01": 2, "2026_03": 1}:
            raise AssertionError(f"Wrong release-local native GO donors: {grouped}")
        print("NATIVE_CANONICAL_RESOLVER_STAGE07=PASS")
        print("RELEASE_LOCAL_DONORS=PASS START=2 END=1")
        m8 = fixture["m8_inputs"]
        publish_raw_annotation_collection(**m8)
        validate_bundle(m8["destination"], deep=True)
        summary = json.loads(
            (m8["destination"] / "08_collection_summary.json").read_text()
        )
        for role in ("START", "END"):
            if summary["by_role"][role]["retrieved_source_rows"] < 1:
                raise AssertionError(f"M8 did not collect the {role} synthetic GAF")
        if summary["annotation_links"] < 2:
            raise AssertionError("Canonical Stage07 donors were not linked by M8")
        print("NATIVE_STAGE07_TO_M8_GAF_COLLECTION=PASS")
        print("SYNTHETIC_ONLY=YES")
        print("REAL_GAF_CONTENTS_READ=NO")
        print("CANONICAL_V2_NATIVE_RESOLVER_M8_SYNTHETIC_STATUS=PASS")


def test_native_canonical_v2_resolver_m8_with_real_dp() -> None:
    """Only run the C++ DP integration where the pinned binary is available."""
    repo = Path(os.environ.get("PROBE_SOURCE_REPO", Path.cwd())).resolve()
    binary = os.environ.get("PROBE_DP_BINARY")
    pinned = repo / "config/canonical_v2.pinned.json"
    if binary is None and pinned.is_file():
        spec = json.loads(pinned.read_text(encoding="utf-8"))
        binary = spec["tools"]["full_dp_binary"]
    if not binary or not Path(binary).is_file():
        pytest.skip("Canonical C++ DP binary is unavailable")
    check(repo, Path(binary).resolve())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path.cwd())
    parser.add_argument("--dp-binary", type=Path, required=True)
    args = parser.parse_args()
    check(args.repo.resolve(), args.dp_binary.resolve())


if __name__ == "__main__":
    main()
